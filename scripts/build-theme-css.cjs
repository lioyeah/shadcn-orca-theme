/**
 * build-theme-css.cjs
 * Concatenates the ordered source manifest into one theme file.
 */

const fs = require("fs");
const path = require("path");

const rootDir = path.join(__dirname, "..");
const sourceDir = path.join(rootDir, "src");
const manifestPath = path.join(sourceDir, "theme-css", "manifest.cjs");
const publicDir = path.join(rootDir, "public");
const distDir = path.join(rootDir, "dist");

function ensureDir(dir) {
	if (!fs.existsSync(dir)) {
		fs.mkdirSync(dir, { recursive: true });
	}
}

const sources = require(manifestPath);
const readSources = (relativePaths) => relativePaths.map((relativePath) => {
	const sourcePath = path.join(sourceDir, relativePath);
	if (!fs.existsSync(sourcePath)) {
		throw new Error(`Theme source not found: ${relativePath}`);
	}
	return fs.readFileSync(sourcePath, "utf8");
});
const prelude = readSources(sources.prelude);
const base = readSources(sources.base);
const components = readSources(sources.components).map((content) =>
	content.replace(/^@layer components \{\n/, "").replace(/\n\}\n$/, ""),
);
const overrides = readSources(sources.overrides);

const combined =
	"/* shadcn/ui Orca Theme (neutral) */\n" +
	"/* Auto-generated by build-theme-css.cjs — do not edit */\n\n" +
	prelude.join("\n\n") +
	"\n\n" +
	base.join("") +
	"\n" +
	"/* ============================================================\n" +
	"   4. COMPONENTS\n" +
	"   ============================================================ */\n\n" +
	"@layer components {\n" +
	components.join("\n") +
	"\n}\n" +
	"\n" +
	overrides.join("");

const outputName = "shadcn.css";

ensureDir(publicDir);
fs.writeFileSync(path.join(publicDir, outputName), combined, "utf8");
console.log(`Built ${path.join(publicDir, outputName)}`);

ensureDir(distDir);
fs.writeFileSync(path.join(distDir, outputName), combined, "utf8");
console.log(`Copied ${outputName} → dist/`);
