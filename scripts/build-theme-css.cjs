/**
 * build-theme-css.cjs
 * Concatenates flavor.css + shadcn-primitives.css + _shared.css → one theme file.
 *
 * Order: tokens first, then shadcn patterns, then Orca component mappings.
 */

const fs = require("fs");
const path = require("path");

const rootDir = path.join(__dirname, "..");
const flavorPath = path.join(rootDir, "src", "flavors", "default.css");
const primitivesPath = path.join(rootDir, "src", "theme-css", "shadcn-primitives.css");
const sharedPath = path.join(rootDir, "src", "theme-css", "_shared.css");
const publicDir = path.join(rootDir, "public");
const distDir = path.join(rootDir, "dist");

function ensureDir(dir) {
	if (!fs.existsSync(dir)) {
		fs.mkdirSync(dir, { recursive: true });
	}
}

const flavor = fs.readFileSync(flavorPath, "utf8");
const primitives = fs.readFileSync(primitivesPath, "utf8");
const shared = fs.readFileSync(sharedPath, "utf8");

const combined =
	"/* shadcn/ui Orca Theme (neutral) */\n" +
	"/* Auto-generated by build-theme-css.cjs — do not edit */\n\n" +
	flavor +
	"\n\n" +
	primitives +
	"\n\n" +
	shared +
	"\n";

const outputName = "shadcn.css";

ensureDir(publicDir);
fs.writeFileSync(path.join(publicDir, outputName), combined, "utf8");
console.log(`Built ${path.join(publicDir, outputName)}`);

ensureDir(distDir);
fs.writeFileSync(path.join(distDir, outputName), combined, "utf8");
console.log(`Copied ${outputName} → dist/`);
